export const getVillageName = (name: string, language: 'en' | 'ta'): string => {
    if (language === 'ta') {
        // Try exact match
        if (VILLAGE_TRANSLATIONS[name]) {
            return VILLAGE_TRANSLATIONS[name];
        }

        // Try case-insensitive match
        const lowerName = name.toLowerCase();
        const key = Object.keys(VILLAGE_TRANSLATIONS).find(k => k.toLowerCase() === lowerName);
        if (key) {
            return VILLAGE_TRANSLATIONS[key];
        }

        // Fallback: If it ends with "Colony", translate that part
        if (lowerName.endsWith(' colony')) {
            const baseName = name.substring(0, name.length - 7).trim();
            const translatedBase = getVillageName(baseName, 'ta');
            if (translatedBase !== baseName) {
                return `${translatedBase} காலனி`;
            }
        }

        // Fallback: If it ends with "Nagar", translate that part
        if (lowerName.endsWith(' nagar')) {
            const baseName = name.substring(0, name.length - 6).trim();
            const translatedBase = getVillageName(baseName, 'ta');
            if (translatedBase !== baseName) {
                return `${translatedBase} நகர்`;
            }
        }
    } else if (language === 'en') {
        // Reverse lookup: Check if the name is a Tamil value and return the English key
        const entry = Object.entries(VILLAGE_TRANSLATIONS).find(([key, value]) => value === name);
        if (entry) {
            return entry[0];
        }
    }
    return name;
};
