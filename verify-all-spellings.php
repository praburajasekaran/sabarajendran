    $t = get_post_meta($pr->ID, '_project_title_tamil', true);
    if (!empty($t)) {
        $new = $t;
        foreach ($corrections as $w => $cor) {
            $new = str_replace($w, $cor, $new);
        }
        if ($new !== $t) {
            update_post_meta($pr->ID, '_project_title_tamil', $new);
